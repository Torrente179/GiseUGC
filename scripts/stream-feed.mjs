#!/usr/bin/env node
/**
 * Streams for the feed's reels: the same video as the feed MP4s
 * (scripts/encode-feed.mjs), repackaged, never re-encoded, into a fragmented
 * MP4 with a byte-range HLS playlist.
 *
 * The feed plays them through Media Source (hls.js; ManagedMediaSource on
 * iPhone), so the page decides what loads and when. The first seconds of the
 * reels around the one on screen are loaded ahead. iPhone's no-preload rule
 * for <video> doesn't apply to that, so a reel starts the moment it is shown.
 *
 * Reads tmp/video-feed/<slug>/{hevc,avc}.mp4 (the encode-feed outputs) and
 * writes:
 *   tmp/video-stream/<slug>/<version>/<codec>.{mp4,m3u8}
 *   src/data/feed-streams.ts
 * With --upload, puts them on R2 at videos/feed/v1/<slug>/<version>/.
 *
 *   node scripts/stream-feed.mjs [--only <slug,slug>] [--upload]
 */
import { existsSync, mkdirSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { r2, run } from './lib/video-encoding.mjs';
import { buildFmp4Playlist } from './lib/fmp4-playlist.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const FEED_VERSION = 'v1';
/** Bump when the packaging changes: the files are cached as immutable. */
const STREAM_VERSION = 's1';
const SOURCE_DIR = path.join(ROOT, 'tmp/video-feed');
const OUT_DIR = path.join(ROOT, 'tmp/video-stream');
const DATA_FILE = path.join(ROOT, 'src/data/feed-streams.ts');

const args = process.argv.slice(2);
const upload = args.includes('--upload');
const onlyIndex = args.indexOf('--only');
const only = onlyIndex >= 0 ? new Set(args[onlyIndex + 1].split(',')) : null;

const probeDuration = async (file) =>
  Number((await run('ffprobe', ['-v', 'error', '-show_entries', 'format=duration', '-of', 'default=nw=1:nk=1', file], { capture: true })).trim());

const slugs = readdirSync(SOURCE_DIR)
  .filter((slug) => existsSync(path.join(SOURCE_DIR, slug, 'avc.mp4')))
  .filter((slug) => !only || only.has(slug))
  .sort();

const streams = {};
const uploads = [];
for (const slug of slugs) {
  const codecs = ['hevc', 'avc'].filter((codec) => existsSync(path.join(SOURCE_DIR, slug, `${codec}.mp4`)));
  const outDir = path.join(OUT_DIR, slug, STREAM_VERSION);
  mkdirSync(outDir, { recursive: true });
  for (const codec of codecs) {
    const source = path.join(SOURCE_DIR, slug, `${codec}.mp4`);
    const media = path.join(outDir, `${codec}.mp4`);
    // Stream copy: same bytes per frame, cut into 1 s fragments.
    await run('ffmpeg', [
      '-v', 'error', '-y', '-i', source, '-map', '0', '-c', 'copy',
      '-movflags', '+empty_moov+default_base_moof', '-frag_duration', '1000000',
      '-f', 'mp4', media,
    ]);
    const playlist = buildFmp4Playlist(media, `${codec}.mp4`);
    const sourceDuration = await probeDuration(source);
    if (Math.abs(playlist.duration - sourceDuration) > 0.15) {
      throw new Error(`${slug}/${codec}: stream lasts ${playlist.duration}s, master ${sourceDuration}s`);
    }
    writeFileSync(path.join(outDir, `${codec}.m3u8`), playlist.text);
    console.log(
      `${slug}/${codec}: ${playlist.segments} segments, ${playlist.duration.toFixed(1)} s, first ${(playlist.firstBytes / 1e6).toFixed(2)} MB`,
    );
    uploads.push({ file: media, key: `${slug}/${STREAM_VERSION}/${codec}.mp4`, type: 'video/mp4' });
    uploads.push({ file: path.join(outDir, `${codec}.m3u8`), key: `${slug}/${STREAM_VERSION}/${codec}.m3u8`, type: 'application/vnd.apple.mpegurl' });
  }
  streams[slug] = codecs;
}

// Upload first: the data file is what makes the site request a stream, and the
// media host caches a 404 for 31 days, so a reel must never be listed before
// its files are on R2 (it would play its MP4 for a month).
if (upload) {
  const { put } = r2(ROOT);
  for (const item of uploads) {
    const key = `videos/feed/${FEED_VERSION}/${item.key}`;
    if (await put(item.file, key, item.type, statSync(item.file).size)) console.log(`↑ ${key}`);
  }
}

if (!only) {
  const body = Object.entries(streams)
    .map(([slug, codecs]) => `  '${slug}': [${codecs.map((codec) => `'${codec}'`).join(', ')}],`)
    .join('\n');
  writeFileSync(
    DATA_FILE,
    `/**
 * AUTO-GENERATED FILE. DO NOT EDIT BY HAND.
 *
 * Generated by: scripts/stream-feed.mjs
 */

/** Folder of the current packaging, under each reel's feed folder. */
export const FEED_STREAM_VERSION = '${STREAM_VERSION}';

/** Reels with a stream on R2, and its codecs (see src/lib/feed-stream.ts). */
export const FEED_STREAMS: Readonly<Record<string, readonly ('hevc' | 'avc')[]>> = {
${body}
};
`,
  );
  console.log(`→ ${path.relative(ROOT, DATA_FILE)}`);
}
